#!/usr/bin/env bash
# shellcheck disable=SC2034,SC1091
# impact-map.sh — system-wide change impact map (i-code-reviewer, mandatory on every change)
# Contract and env: see lib.sh (--json, I_GATE=report|block, I_REPO, exit 0/1/2).
set -o pipefail
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
T_NAME="impact-map"; T_SUMMARY="map changed files to consumers, jobs, tables, queries and schedules"
T_OPTIONS="  --base <ref>         compare against this ref (default: main, origin/main, then HEAD~1)
Text mode prints the markdown section '## 10. Change Impact Analysis (i-code-reviewer)' for .impact-analysis/<branch>.md."
BASE=""
t_parse "base=BASE" "$@"; t_init

if [ -z "$BASE" ]; then
    for c in main origin/main HEAD~1; do git rev-parse --verify -q "$c" >/dev/null 2>&1 && { BASE="$c"; break; }; done
fi
changed=""
if [ -n "$BASE" ]; then changed="$(git diff --name-only --diff-filter=ACMRT "$BASE"...HEAD 2>/dev/null)"; fi
changed="$(printf '%s\n%s\n%s\n' "$changed" "$(git diff --name-only --diff-filter=ACMRT HEAD 2>/dev/null)" "$(git ls-files --others --exclude-standard 2>/dev/null)" | sed '/^$/d' | LC_ALL=C sort -u)"

SQL=""; PIPE=""; PROMPT=""; OT=""; IAC=""; SCHED=""; TESTS=""
while IFS= read -r f; do
    [ -n "$f" ] || continue
    l="$(printf '%s' "$f" | tr '[:upper:]' '[:lower:]')"
    case "$l" in *.sql) SQL="$SQL$f
" ;; esac
    case "$l" in *glue*|*etl*|*pipeline*|*dag*|*airflow*|*athena*|*stepfunction*|*step_function*|*lambda*) PIPE="$PIPE$f
" ;; esac
    case "$l" in prompts/*|*/prompts/*|*.prompt|*system_prompt*|*prompt*.md|.llm_settings/agents/*|.llm_settings/skills/*|agents-src/*|*/agents/*|*agent*.md) PROMPT="$PROMPT$f
" ;; esac
    case "$l" in *telemetry*|*modbus*|*dnp3*|*iec61850*|*scada*|*bess*|*/ot/*|ot/*) OT="$OT$f
" ;; esac
    case "$l" in *.tf|dockerfile*|*/dockerfile*|*terraform*|*cloudformation*|*k8s*|*helm*) IAC="$IAC$f
" ;; esac
    case "$l" in *cron*|*schedule*|*eventbridge*|.github/workflows/*) SCHED="$SCHED$f
" ;; esac
    case "$l" in test_*|*_test.*|tests/*|*/tests/*|*.bats) TESTS="$TESTS$f
" ;; esac
done <<EOF2
$changed
EOF2

CONS=""   # lines "file<TAB>consumer1 consumer2"
while IFS= read -r f; do
    [ -n "$f" ] && [ -f "$f" ] || continue
    mod="$(basename "$f")"; mod="${mod%.*}"
    [ "${#mod}" -ge 3 ] || continue
    refs="$(git grep -l -w -F -- "$mod" 2>/dev/null | /usr/bin/grep -vxF "$f" | head -20 | tr '\n' ' ')"
    [ -n "$refs" ] && CONS="$CONS$f$(printf '\t')${refs% }
"
done <<EOF3
$changed
EOF3

AGENTS="i-code-reviewer"
[ -n "$SQL$PIPE$PROMPT$OT" ] && AGENTS="$AGENTS i-data-ai-ot"
[ -n "$IAC" ] && AGENTS="$AGENTS i-security-scanner"
[ -n "$changed" ] && AGENTS="$AGENTS i-unit-tdd"
[ -n "$SCHED$IAC" ] && AGENTS="$AGENTS i-release-gate"

jarr() { local first=true x; printf '['; while IFS= read -r x; do [ -n "$x" ] || continue; $first || printf ','; first=false; printf '"%s"' "$(t_json_escape "$x")"; done <<EOF4
$1
EOF4
printf ']'; }

if $T_JSON; then
    printf '{"script":"impact-map","gate":"%s","status":"pass","repo":"%s","base":"%s","changed":%s,"consumers":[' \
        "$T_GATE" "$(t_json_escape "$T_REPO")" "$(t_json_escape "${BASE:-none}")" "$(jarr "$changed")"
    first=true
    while IFS="$(printf '\t')" read -r f refs; do
        [ -n "$f" ] || continue
        $first || printf ','; first=false
        printf '{"file":"%s","referenced_by":%s}' "$(t_json_escape "$f")" "$(jarr "$(printf '%s' "$refs" | tr ' ' '\n')")"
    done <<EOF5
$CONS
EOF5
    printf '],"categories":{"sql":%s,"pipeline":%s,"prompt":%s,"ot":%s,"iac":%s,"schedule":%s,"tests":%s},"agents":%s,"checks":[{"id":"map","status":"pass","detail":"%s changed file(s)"}]}\n' \
        "$(jarr "$SQL")" "$(jarr "$PIPE")" "$(jarr "$PROMPT")" "$(jarr "$OT")" "$(jarr "$IAC")" "$(jarr "$SCHED")" "$(jarr "$TESTS")" \
        "$(jarr "$(printf '%s' "$AGENTS" | tr ' ' '\n')")" "$(printf '%s\n' "$changed" | sed '/^$/d' | wc -l | tr -d ' ')"
    exit 0
fi

list() { if [ -n "$1" ]; then printf '%s' "$1" | sed '/^$/d; s/^/  - `/; s/$/`/'; printf '\n'; else printf '  - none\n'; fi; }
printf '## 10. Change Impact Analysis (i-code-reviewer)\n\n'
printf 'Base: `%s` · %s changed file(s) · generated by scripts/testing/impact-map.sh\n\n' "${BASE:-none}" "$(printf '%s\n' "$changed" | sed '/^$/d' | wc -l | tr -d ' ')"
printf '### Changed files and their consumers\n\n'
if [ -n "$changed" ]; then
    while IFS= read -r f; do
        [ -n "$f" ] || continue
        refs="$(printf '%s' "$CONS" | awk -F'\t' -v f="$f" '$1==f{print $2}')"
        printf -- '- `%s` ← %s\n' "$f" "${refs:-no other file references this module}"
    done <<EOF6
$changed
EOF6
else printf -- '- none\n'; fi
printf '\n### Jobs, tables, queries, schedules\n\n- SQL / queries / tables:\n'; list "$SQL"
printf -- '- Pipelines and jobs:\n'; list "$PIPE"
printf -- '- Schedules and workflows:\n'; list "$SCHED"
printf -- '- Prompts and agents:\n'; list "$PROMPT"
printf -- '- OT / telemetry paths:\n'; list "$OT"
printf -- '- Infrastructure as code:\n'; list "$IAC"
printf '\n### Agents to involve\n\n'
for a in $AGENTS; do printf -- '- %s\n' "$a"; done
exit 0
